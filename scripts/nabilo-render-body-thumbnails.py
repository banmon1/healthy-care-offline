"""Build the small offline list thumbnails from the bundled MIT body geometry.

Run with Python and PyMuPDF 1.27.2.3. The mobile build uses the generated PNGs.
"""
from html import escape
from pathlib import Path
import json
import pymupdf

root = Path(__file__).resolve().parents[1]
output = root / 'assets' / 'body-thumbnails'
output.mkdir(exist_ok=True)
source = json.loads((root / 'src/opengym/body-paths.json').read_text(encoding='utf8'))['male']
neutral_parts = {'hands', 'knees', 'ankles', 'feet', 'head', 'hair'}
back_view = {'upper-back', 'lower-back', 'trapezius', 'back-deltoids', 'triceps', 'gluteal', 'hamstring'}
images = {}
for side, geometry in source.items():
    muscles = {}
    for part, paths in geometry['p'].items():
        muscle = {'adductors': 'adductor', 'deltoids': side + '-deltoids'}.get(part, part)
        muscles[muscle] = paths
    selected = [m for m in muscles if m not in neutral_parts and (m in back_view) == (side == 'back')]
    if side == 'front':
        selected.append('default')
    for active in sorted(selected):
        paths = []
        for muscle, segments in muscles.items():
            fill = '#F06B2A' if muscle == active else '#E9EBEE' if muscle in neutral_parts else '#DADDE1'
            for segment in segments:
                paths.append(f'<path d="{escape(segment)}" fill="{fill}" stroke="white" stroke-width="2.1"/>')
        svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="144" height="228" viewBox="{geometry["vb"]}">{"".join(paths)}</svg>'
        name = f'{active}.png'
        with pymupdf.open(stream=svg.encode(), filetype='svg') as document:
            document[0].get_pixmap(alpha=True).save(output / name)
        images[active] = name

lines = ["// Generated by scripts/nabilo-render-body-thumbnails.py.", "import type { ImageSourcePropType } from 'react-native';",
         "export const bodyThumbnails: Record<string, ImageSourcePropType> = {"]
lines.extend(f"  '{muscle}': require('../assets/body-thumbnails/{name}')," for muscle, name in sorted(images.items()))
lines.append("};")
(root / 'src/body-thumbnails.ts').write_text('\n'.join(lines) + '\n', encoding='utf8')
