import { readFile, writeFile, mkdir, copyFile } from 'node:fs/promises';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';

const source=process.argv[2];
if (!source) throw new Error('Pass the exercise-images repository checkout.');
const revision=execFileSync('git',['-C',source,'rev-parse','HEAD'],{encoding:'utf8'}).trim();
const catalogue=JSON.parse(await readFile('src/opengym/catalogue.json','utf8'));
const data=JSON.parse(await readFile(join(source,'exercises.json'),'utf8'));
const normalise=name=>name.toLowerCase().replace(/[^a-z0-9]+/g,' ').trim();
const byId=new Map(data.exercises.map(item=>[item.id,item]));
const byName=new Map();
for (const item of data.exercises) {
  for (const name of [item.name,...item.aliases]) byName.set(normalise(name),item);
}
for (const variant of data.variants) {
  if (!variant.difference && !variant.equipment && byId.has(variant.imageOf)) byName.set(normalise(variant.name),byId.get(variant.imageOf));
}
const reviewed={
  'og-0662':'push-up','og-1197':'bodyweight-squat','og-0463':'plank',
  'og-0289':'dumbbell-chest-press','og-0336':'dumbbell-lunge',
  'og-0334':'lateral-raises','og-0003':'bicycle-crunch','og-0145':'glute-bridge',
  'og-0417':'dumbbell-calf-raise','og-0198':'lat-pulldown','og-0861':'seated-cable-row',
  'og-0739':'leg-press','og-0294':'biceps-curl','og-3094':'jumping-jacks',
};
function compatibleEquipment(exercise,illustration) {
  const equipment=exercise.equipment;
  const choices=illustration.equipment;
  if (equipment==='body weight') return choices.length===0;
  if (/machine|ergometer/.test(equipment)) return choices.includes('machine') || choices.includes('cardio-machine');
  const key=({'olympic barbell':'barbell','ez barbell':'ez-bar','band':'band','resistance band':'band','stability ball':'stability-ball','medicine ball':'medicine-ball'})[equipment] ?? equipment;
  return choices.includes(key);
}
const mappings=[];
for (const exercise of catalogue) {
  // Variants may have different grip, range or equipment. Keep their body map until reviewed individually.
  if (exercise.variantOf) continue;
  const illustration=reviewed[exercise.id] ? byId.get(reviewed[exercise.id]) : byName.get(normalise(exercise.englishName));
  if (illustration && compatibleEquipment(exercise,illustration)) mappings.push([exercise.id,illustration.id]);
}
const used=[...new Set(mappings.map(([,id])=>id))].sort();
const directory='assets/illustrations';
await mkdir(directory,{recursive:true});
const entries=[];
for (const id of used) {
  const illustration=byId.get(id);
  const frames=[];
  for (const name of illustration.frames) {
    const file=illustration.images[name];
    const target=`${id}-${name}.webp`;
    await copyFile(join(source,file),join(directory,target));
    frames.push(`require('../assets/illustrations/${target}')`);
  }
  entries.push(`  '${id}': {frames:[${frames.join(',')}],width:${illustration.width},height:${illustration.height}}`);
}
await writeFile('src/exercise-illustrations.ts',[
  '// Generated by scripts/nabilo-import-illustrations.mjs. See assets/illustrations/SOURCE.md.',
  "import type { ImageSourcePropType } from 'react-native';",
  'export type ExerciseIllustration = {frames:ImageSourcePropType[];width:number;height:number};',
  'const library:Record<string,ExerciseIllustration> = {',entries.join(',\n'),'};',
  'export const exerciseIllustrations:Record<string,ExerciseIllustration> = {',
  mappings.map(([id,asset])=>`  '${id}':library['${asset}']`).join(',\n'),'};','',
].join('\n'));
await copyFile(join(source,'LICENSE'),join(directory,'LICENSE-CC0.txt'));
await copyFile(join(source,'README.md'),join(directory,'README-upstream.md'));
await writeFile(join(directory,'SOURCE.md'),[
  '# Exercise illustrations',
  `Source: https://github.com/MarvinNazari/exercise-images/tree/${revision}`,
  'Licence: CC0 1.0. Original images copied unchanged. The upstream describes these as AI-generated illustrations checked by eye, with no professional coaching review. See README-upstream.md for its limitations.',
  'Matching uses exact English names/aliases and compatible equipment, with explicit mappings for the built-in routines. OpenGym variants are excluded until individually reviewed.',
  `${used.length} illustration sets map to ${mappings.length} primary OpenGym entries. Unmatched exercises retain the anatomical body map.`,
  '',
].join('\n'));
await writeFile(join(directory,'mapping.json'),JSON.stringify({revision,mappings},null,2));
console.log(`${mappings.length} primary OpenGym entries; ${used.length} distinct illustration sets.`);
